#!/usr/bin/env python3
"""Render `bench/results.jsonl` into `docs/benchmarks.md`.

One row per repository per mode, the latest run of each; the model and
the systemap version named on every row, and the dollars per module for
a first map. The table is the measurement the README quotes; when nothing
has been measured it says so, and a test keeps the committed file equal
to what this script renders. Standard library only; `systemap` itself is
not involved.

    python3 bench/table.py [--results bench/results.jsonl] [--out docs/benchmarks.md] [--check]
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Iterable
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "bench" / "results.jsonl"
OUT = ROOT / "docs" / "benchmarks.md"
MODES = ("first-map", "maintenance")
COLUMNS = (
    "repository",
    "mode",
    "modules",
    "systemap",
    "model",
    "turns",
    "minutes",
    "dollars",
    "dollars per module",
    "check",
    "judgement",
    "run",
    "skill first",
    "date",
)

HEAD = """# Benchmarks

Generated by `bench/table.py` from `bench/results.jsonl`; do not edit by
hand. One row per repository per mode (the latest run of each), written
by `bench/run.sh`, which runs the documented headless recipe and records
what the session's result event says: the model, the turns, the minutes,
the dollars. `check` and `judgement` are `systemap check` and `systemap
judgement --strict` run after the session; `run` says whether the session
finished on its own or was cut off; `skill first` whether its first tool
call was the systemap skill, as the recipe requires.

Before any of it was built, two numbers were set to be failed against: a
first map at most 0.15 dollars per module, and a maintenance run at most
15 turns and 2 dollars on a medium pull request. The rows below are what
happened. Four of the six first maps came in under 0.15 and two did
not (0.159 and 0.177). The maintenance runs came in at 2.31, 4.39 and
2.50 dollars, over the 2 dollar line, and at 51, 63 and 46 turns, well
over the 15 the target named, because the maintenance path runs delta,
refresh, check and judgement rather than the two steps that number
assumed. Neither target was moved after the fact.
"""

EMPTY = "No run recorded yet: the table is empty until a repository is measured."


def rows(lines: Iterable[str]) -> list[dict[str, Any]]:
    """The latest run per repository and mode, in repository then mode order."""
    latest: dict[tuple[str, str], dict[str, Any]] = {}
    for line in lines:
        line = line.strip()
        if not line:
            continue
        row = json.loads(line)
        key = (str(row.get("repository", "")), str(row.get("mode", "")))
        if key not in latest or str(row.get("date", "")) >= str(latest[key].get("date", "")):
            latest[key] = row
    order = {mode: k for k, mode in enumerate(MODES)}
    return [
        latest[key] for key in sorted(latest, key=lambda k: (k[0], order.get(k[1], len(order))))
    ]


def _cell(value: Any) -> str:
    if value is None or value == "":
        return "-"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, float):
        return f"{value:.3f}".rstrip("0").rstrip(".") if value != int(value) else f"{int(value)}"
    return str(value).replace("|", "\\|")


def _per_module(row: dict[str, Any]) -> Any:
    dollars, modules = row.get("dollars"), row.get("modules")
    if row.get("mode") != "first-map" or not isinstance(dollars, int | float) or not modules:
        return None
    return round(dollars / modules, 3)


def _line(row: dict[str, Any]) -> str:
    cells = [
        row.get("repository"),
        row.get("mode"),
        row.get("modules"),
        row.get("systemap"),
        row.get("model"),
        row.get("turns"),
        row.get("minutes"),
        row.get("dollars"),
        _per_module(row),
        row.get("check"),
        row.get("judgement"),
        row.get("run"),
        row.get("first_tool_ok"),
        str(row.get("date", ""))[:10],
    ]
    return "| " + " | ".join(_cell(c) for c in cells) + " |"


def render(table: list[dict[str, Any]]) -> str:
    if not table:
        return HEAD + "\n" + EMPTY + "\n"
    out = [HEAD, "| " + " | ".join(COLUMNS) + " |", "|" + "---|" * len(COLUMNS)]
    out += [_line(row) for row in table]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="render the benchmark table")
    parser.add_argument("--results", default=str(RESULTS))
    parser.add_argument("--out", default=str(OUT))
    parser.add_argument(
        "--check", action="store_true", help="exit 1 when the file differs from the render"
    )
    args = parser.parse_args(argv)
    results = Path(args.results)
    lines = results.read_text(encoding="utf-8").splitlines() if results.is_file() else []
    text = render(rows(lines))
    out = Path(args.out)
    if args.check:
        current = out.read_text(encoding="utf-8") if out.is_file() else ""
        if current != text:
            sys.stderr.write(f"{out} differs from the render; run: python3 bench/table.py\n")
            return 1
        sys.stdout.write(f"{out} is current\n")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    sys.stdout.write(f"wrote {out}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
